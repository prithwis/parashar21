from pathlib import Path
from datetime import datetime
from zoneinfo import ZoneInfo
import pypandoc
from docx import Document
from docx.shared import Inches, Pt
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Inches, Pt, RGBColor
from docx.enum.text import WD_TAB_ALIGNMENT
from docx.oxml import OxmlElement
from docx.oxml.ns import qn

def markdownToDocx(mdFile, personID, question, provider, model):

    docxFile = str(Path(mdFile).with_suffix(".docx"))

    # Convert Markdown to Word
    pypandoc.convert_file(
        mdFile, "docx", format="md",
        outputfile=docxFile
    )

    doc = Document(docxFile)
    section = doc.sections[0]

    section.top_margin = Inches(0.85)
    section.bottom_margin = Inches(0.75)

    section.page_width = Inches(8.27)
    section.page_height = Inches(11.69)
    section.left_margin = Inches(1)
    section.right_margin = Inches(1)

    # Header: KHONA21
    header = section.header.paragraphs[0]
    header.alignment = WD_ALIGN_PARAGRAPH.LEFT

    run = header.add_run("KHONA21")
    run.font.name = "Georgia"
    run.font.size = Pt(18)
    run.font.bold = True
    run.font.color.rgb = RGBColor(160, 0, 0)

    # Crimson separator line
    pPr = header._p.get_or_add_pPr()
    borders = OxmlElement("w:pBdr")
    bottom = OxmlElement("w:bottom")

    for key, value in {
        "val": "single",
        "sz": "8",
        "color": "A00000",
        "space": "8"
    }.items():
        bottom.set(qn(f"w:{key}"), value)

    borders.append(bottom)
    pPr.append(borders)

    # Report identification, inserted before the answer
    first = doc.paragraphs[0]

    p = first.insert_paragraph_before()
    p.add_run("Person ID: ").bold = True
    p.add_run(personID)

    p = first.insert_paragraph_before()
    p.add_run("Question: ").bold = True
    p.add_run(question)

    first.insert_paragraph_before("")

    

    # Footer
    footer = section.footer.paragraphs[0]
    footer.alignment = WD_ALIGN_PARAGRAPH.LEFT

    page_width = section.page_width - section.left_margin - section.right_margin
    #page_width = Inches(8.27) - section.left_margin - section.right_margin
    footer.paragraph_format.tab_stops.add_tab_stop(
        page_width, WD_TAB_ALIGNMENT.RIGHT
    )

    timestamp = datetime.now(
        ZoneInfo("Asia/Kolkata")
    ).strftime("%d %B %Y, %H:%M IST")

    run = footer.add_run(f"Generated: {timestamp}\tPage ")
    run.font.name = "Georgia"
    run.font.size = Pt(9)
    run.font.color.rgb = RGBColor(110, 110, 110)

    # Automatic page number
    field = OxmlElement("w:fldSimple")
    field.set(qn("w:instr"), "PAGE")
    footer._p.append(field)

    # Word document properties
    props = doc.core_properties

    props.author = "Prithwis Mukerjee"
    props.title = f"Khona21 | Horoscope Interpretation | {personID}"
    props.subject = "AI-assisted Jyotisha interpretation"

    props.comments = (
    "Khona21 — Where ancient Jyotisha meets artificial intelligence. "
    "Part of the Parashar21 project.\n"
    "GitHub: https://github.com/prithwis/parashar21\n"
    "Blog: https://parashar21.blogspot.com/"
    )

    props.keywords = "Khona21, Parashar21, Jyotisha, AI, Horoscope"

    p = doc.add_paragraph()
    p.add_run(f"Generated by: {provider.upper()} | {model}").italic = True
    p.runs[0].font.size = Pt(9)
    p.runs[0].font.color.rgb = RGBColor(110, 110, 110)

    doc.save(docxFile)

    print(f"Saved: {docxFile}")
    return docxFile